    public static InteractionChoice Choice(InteractionAction action) =>
        Groups.SelectMany(g => g.Choices).First(c => c.Action == action);
    public static InteractionGroup Group(InteractionAction action) =>
        Groups.First(g => g.Choices.Any(c => c.Action == action));
